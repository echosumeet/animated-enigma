"""Regenerate every number and the figure used in the README.

    PYTHONPATH=src python benchmarks/run_benchmarks.py [--quick] [--no-figures]
"""

from __future__ import annotations

import argparse
import io
import time
from pathlib import Path

import pandas as pd

from scmplatform import __version__
from scmplatform.backtest import Gate, champion_challenger, check_gate, rolling_backtest
from scmplatform.contracts import demand_panel_contract, diff_contracts, validate
from scmplatform.datagen import PanelConfig, inject_quality_faults, make_panel
from scmplatform.features import audit_features, build_features, default_specs, leaky_specs
from scmplatform.monitoring import drift_over_time, drift_report, slice_performance

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "docs" / "drift_over_time.png"


def md(frame: pd.DataFrame, floatfmt: str = "{:.4f}") -> str:
    """Markdown table without a third-party tabulate dependency."""
    f = frame.copy()
    for c in f.columns:
        if pd.api.types.is_float_dtype(f[c]):
            f[c] = f[c].map(lambda v: floatfmt.format(v))
    header = "| " + " | ".join(str(c) for c in f.columns) + " |"
    sep = "| " + " | ".join("---" for _ in f.columns) + " |"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in f.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="smaller panel, fewer folds")
    ap.add_argument("--no-figures", action="store_true")
    args = ap.parse_args()

    cfg = PanelConfig(n_skus=12 if args.quick else 40, n_days=360 if args.quick else 540, seed=7)
    folds = 2 if args.quick else 4
    t0 = time.perf_counter()
    panel = make_panel(cfg)
    contract = demand_panel_contract()
    as_of = panel["date"].max()
    out = io.StringIO()
    w = out.write

    w(f"# Benchmark results\n\n`scmplatform` {__version__}. Generated by "
      f"`PYTHONPATH=src python benchmarks/run_benchmarks.py"
      f"{' --quick' if args.quick else ''}`.\n\n")
    w(f"Synthetic panel: {cfg.n_skus} SKUs x {cfg.n_days} days = {len(panel):,} rows, "
      f"seed {cfg.seed}. Daily demand is a multiplicative model (weekly and annual "
      f"seasonality, linear trend, promotion lift, constant-elasticity price response) "
      f"drawn from a Poisson distribution. A permanent +{cfg.drift_price_shift:.0%} price "
      f"step is applied to one third of the SKUs from day "
      f"{int(cfg.n_days * cfg.drift_start_frac)} onward to create genuine drift.\n\n")

    # 1 -- contract validation ------------------------------------------------------
    clean = validate(panel, contract, now=as_of)
    faulty = validate(inject_quality_faults(panel), contract, now=as_of)
    w("## 1. Data contract validation\n\n")
    w(f"- clean feed: `{clean.summary()}`\n- faulted feed: `{faulty.summary()}`\n\n")
    w(md(faulty.to_frame(), "{:.0f}") + "\n\n")

    proposed = demand_panel_contract("1.1.0")
    proposed = type(proposed)(
        name=proposed.name,
        version="1.1.0",
        columns=tuple(c for c in proposed.columns if c.name != "on_hand"),
        primary_key=proposed.primary_key,
        freshness_column=proposed.freshness_column,
        max_age_days=1.0,
    )
    diff = diff_contracts(contract, proposed)
    w(f"Contract change 1.0.0 -> 1.1.0: **{diff.summary()}**\n\n")
    for item in diff.breaking:
        w(f"- breaking: {item}\n")
    w("\n")

    # 2 -- leakage audit ------------------------------------------------------------
    clean_findings = audit_features(panel, default_specs())
    leaky_findings = audit_features(panel, leaky_specs())
    w("## 2. Point-in-time audit\n\n")
    w(f"- production feature set ({len(default_specs())} specs): "
      f"**{len(clean_findings)} findings**\n")
    w(f"- feature set with two seeded bugs ({len(leaky_specs())} specs): "
      f"**{len(leaky_findings)} findings**\n\n")
    for f in leaky_findings:
        w(f"- `{f.feature}` [{f.check}] {f.detail}\n")
    w("\n")

    # 3 -- backtest and gate --------------------------------------------------------
    gate = Gate()
    champion = rolling_backtest(panel, default_specs(), label="champion", horizon=14, folds=folds)
    challenger = rolling_backtest(
        panel, default_specs(), label="challenger", horizon=14, folds=folds, bias_adjustment=0.85
    )
    cg, hg = check_gate(champion, gate), check_gate(challenger, gate)
    decision = champion_challenger(champion, challenger, gate)
    w("## 3. Backtest gate and champion/challenger\n\n")
    w(f"Expanding-window backtest, {folds} folds, 14-day horizon. Gate: "
      f"wMAPE <= {gate.max_wmape}, |bias| <= {gate.max_abs_bias}, "
      f"cost/unit <= {gate.max_cost_per_unit}.\n\n")
    w(f"- champion: `{cg.summary()}`\n- challenger (predictions scaled 0.85): `{hg.summary()}`\n")
    w(f"- promotion decision: **{'PROMOTE' if decision.promote else 'HOLD'}** -- "
      f"{decision.rationale}\n\n")
    w(md(decision.as_frame()) + "\n\n")

    # 4 -- monitoring ---------------------------------------------------------------
    feats = build_features(panel, default_specs()).dropna()
    split = feats["date"].quantile(0.7)
    cols = [s.name for s in default_specs()]
    drift = drift_report(feats[feats["date"] <= split], feats[feats["date"] > split], cols)
    slices = slice_performance(champion.predictions, ["category"])
    w("## 4. Feature drift (pre-split reference vs post-split current)\n\n")
    w(md(drift) + "\n\n")
    w("## 5. Slice-level performance\n\n")
    w(f"{slices.summary()}\n\n")
    w(md(slices.table.drop(columns=["flag"]).assign(flag=slices.table["flag"].astype(str))) + "\n\n")

    # 6 -- decision quality ---------------------------------------------------------
    dq = champion.decisions()
    w("## 6. Decision quality (periodic-review order-up-to policy)\n\n")
    w(md(pd.DataFrame([{k: v for k, v in dq.as_dict().items()}]), "{:.4f}") + "\n\n")
    w(f"Realised inventory cost is {dq.realised_cost / max(dq.irreducible_cost, 1e-9):.2f}x the "
      f"cost a perfect point forecast would still incur under the same service target; "
      f"the gap ({dq.regret:,.0f} cost units over {dq.units:,.0f} units of demand, "
      f"{dq.regret_per_unit:.4f} per unit) is the part attributable to forecast error.\n\n")

    if not args.no_figures:
        from scmplatform.plots import plot_drift_over_time

        ref_end = feats["date"].quantile(0.5)
        series = drift_over_time(
            feats, ["price_lag_0", "units_ma_28", "on_hand_lag_1", "units_sd_28"], ref_end
        )
        plot_drift_over_time(series, FIG)
        w(f"## 7. Figure\n\n`docs/{FIG.name}` -- PSI per 30-day monitoring window against a "
          f"fixed reference period ending {ref_end:%Y-%m-%d}.\n\n")

    w(f"Total runtime {time.perf_counter() - t0:.1f}s.\n")
    (Path(__file__).parent / "results.md").write_text(out.getvalue(), encoding="utf-8")
    print(out.getvalue())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
