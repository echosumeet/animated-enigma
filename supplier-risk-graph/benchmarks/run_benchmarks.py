"""Regenerate every number in the README, plus the figure.

    PYTHONPATH=src python benchmarks/run_benchmarks.py [--quick]
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

from riskgraph import (
    degree_ranking,
    expand,
    generate_network,
    geographic_hhi,
    hhi_by_tier,
    hidden_dependencies,
    rank_spofs,
    score_actions,
    simulate,
    sole_source_parts,
    supplier_hhi,
)
from riskgraph.figures import spof_figure

ROOT = Path(__file__).resolve().parents[1]
SEEDS = [7, 11, 23, 41, 57]


def money(x: float) -> str:
    return f"{x / 1e6:,.1f}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="fewer seeds and trials, for CI")
    args = ap.parse_args(argv)
    seeds = SEEDS[:2] if args.quick else SEEDS
    trials = 300 if args.quick else 2000
    mit_trials = 200 if args.quick else 800

    started = time.time()
    lines: list[str] = ["# Benchmark results", ""]
    lines.append(f"Generated by `benchmarks/run_benchmarks.py`{' --quick' if args.quick else ''}.")
    lines.append("")

    # -- structure and concentration across seeds
    lines += [
        "## Network instances and concentration",
        "",
        "| seed | parts | suppliers | sites | sole-sourced parts | tier-1 HHI | tier-3 HHI | geo HHI |",
        "|---|---|---|---|---|---|---|---|",
    ]
    detect_hits = 0
    detect_top3 = 0
    for seed in seeds:
        net = generate_network(seed=seed)
        fg = net.finished_goods()[0].part_id
        tiers = hhi_by_tier(net, fg)
        geo, _ = geographic_hhi(net, fg)
        lines.append(
            f"| {seed} | {len(net.parts)} | {len(net.suppliers)} | {len(net.sites)} | "
            f"{len(sole_source_parts(net))} | {tiers.get(1, 0):.3f} | {tiers.get(3, 0):.3f} | {geo:.3f} |"
        )
        found = [h.supplier_id for h in hidden_dependencies(net, fg)]
        planted = net.site_supplier(net.sources("MAT-CRIT")[0].site_id)
        if found and found[0] == planted:
            detect_hits += 1
        if planted in found[:3]:
            detect_top3 += 1

    lines += ["", f"Planted diamond recovered as the top-ranked hidden dependency in "
                  f"{detect_hits}/{len(seeds)} instances, and inside the top three in "
                  f"{detect_top3}/{len(seeds)}.", ""]

    # -- the headline instance
    net = generate_network(seed=7)
    fg = net.finished_goods()[0].part_id
    revenue = sum(p.annual_revenue for p in net.finished_goods())
    rows = expand(net, fg)
    lines += [
        "## Reference instance (seed 7)",
        "",
        f"- {len(net.parts)} parts, {len(net.suppliers)} suppliers, {len(net.sites)} sites, "
        f"{len(net.bom)} BOM edges, {len(net.supply)} sourcing edges",
        f"- {fg} expands to {len(rows)} parts across {max(r.depth for r in rows)} tiers",
        f"- portfolio revenue ${money(revenue)}M, supplier HHI {supplier_hhi(net, fg):.3f}",
        "",
        "### Hidden shared sub-tier suppliers",
        "",
        "| supplier | depth | tier-1 branches reached | parts | revenue at risk, all products ($M) | share of FG-1 |",
        "|---|---|---|---|---|---|",
    ]
    for h in hidden_dependencies(net, fg)[:5]:
        lines.append(
            f"| {h.supplier_id} | {h.depth} | {h.tier1_suppliers} | {h.parts} | "
            f"{money(h.revenue_at_risk)} | {h.revenue_share:.0%} |"
        )

    lines += [
        "",
        "### Single points of failure, ranked by revenue at risk",
        "",
        "| node | revenue at risk ($M) | share | articulation point | sole-sourced parts | mean recovery (d) |",
        "|---|---|---|---|---|---|",
    ]
    spofs = rank_spofs(net, top_n=8)
    for s in spofs:
        lines.append(
            f"| {s.node_id} | {money(s.revenue_at_risk)} | {s.revenue_share:.0%} | "
            f"{'yes' if s.articulation else 'no'} | {s.sole_source_parts} | {s.mean_recovery_days:.0f} |"
        )
    top_by_degree = degree_ranking(net, top_n=8)
    overlap = len(set(top_by_degree) & {s.node_id for s in spofs})
    lines += ["", f"Degree centrality agrees with the revenue-at-risk ranking on {overlap} of the "
                  f"top {len(spofs)} nodes.", ""]

    # -- simulation
    lines += [
        "## Monte Carlo disruption simulation",
        "",
        f"{trials} trials, one-year horizon, common random numbers across scenarios.",
        "",
        "| scenario | P(shortfall) | expected loss ($M) | p95 loss ($M) | mean TTR (d) | p95 TTR (d) | service level |",
        "|---|---|---|---|---|---|---|",
    ]
    scenarios = {
        "baseline": simulate(net, trials=trials, seed=11),
        "no ramp-up flex": simulate(net, trials=trials, seed=11, flex=1.0),
        "4 weeks buffer on MAT-CRIT": simulate(net, trials=trials, seed=11, buffers={"MAT-CRIT": 28.0}),
    }
    for name, r in scenarios.items():
        lines.append(
            f"| {name} | {r.p_any_impact:.1%} | {money(r.expected_loss)} | {money(r.p95_loss)} | "
            f"{r.mean_ttr_days:.0f} | {r.p95_ttr_days:.0f} | {r.mean_service_level:.1%} |"
        )

    # -- mitigation
    targets = [r.part_id for r in rows if r.sole_source and r.depth >= 2][:2]
    base, actions = score_actions(net, targets, trials=mit_trials, seed=11)
    lines += [
        "",
        "## Mitigation ranking",
        "",
        f"{mit_trials} trials per action, scored against a baseline expected loss of "
        f"${money(base.expected_loss)}M.",
        "",
        "| action | target | annual cost ($) | expected loss after ($M) | risk reduction ($) | reduction per $1 |",
        "|---|---|---|---|---|---|",
    ]
    for a in actions:
        lines.append(
            f"| {a.action} | {a.target} | {a.annual_cost:,.0f} | {money(a.expected_loss_after)} | "
            f"{a.risk_reduction:,.0f} | {a.reduction_per_dollar:.2f} |"
        )

    fig = spof_figure(net, ROOT / "docs" / "network_spof.png")
    elapsed = time.time() - started
    lines += ["", f"Figure written to `{fig.relative_to(ROOT)}`.",
              "", f"Total runtime {elapsed:.1f}s on one core.", ""]

    out = ROOT / "benchmarks" / "results.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
