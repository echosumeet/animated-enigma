"""Regenerate every number in the README, plus the figure.

    PYTHONPATH=src python benchmarks/run_benchmarks.py [--quick]
"""

from __future__ import annotations

import argparse
import os
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from tradedoc.evaluate import run  # noqa: E402
from tradedoc.figures import stp_curve  # noqa: E402
from tradedoc.generate import NoiseConfig  # noqa: E402
from tradedoc.sweep import operating_point  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BUDGETS = (0.02, 0.03, 0.05, 0.10)
REPORT_THRESHOLDS = (0.00, 0.40, 0.56, 0.72, 0.80, 0.88, 0.96)


def _md_table(header, rows) -> str:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="smaller corpus for CI")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args(argv)
    n = 40 if args.quick else 200

    t0 = time.time()
    base = run(n, args.seed, confirm="high_value")
    n_docs = len(base.results)
    doc_acc = sum(base.correct) / n_docs

    lines = ["# Benchmark results", "",
             f"Generated by `benchmarks/run_benchmarks.py` (seed {args.seed}, "
             f"{n} shipments = {n_docs} documents).", "",
             "Data-generating process: each shipment emits a commercial invoice, a "
             "packing list and a bill of lading from one ground-truth record, across "
             "three layout variants, eight vendors in eight countries, six currencies, "
             "all eleven Incoterms 2020 rules and three date formats. Noise is applied "
             "as three independent mechanisms: per-character OCR substitution at "
             f"{NoiseConfig().char_corruption_rate:.3f}, field omission at "
             f"{NoiseConfig().field_dropout_rate:.2f} per printed field, and a real "
             f"cross-document inconsistency in {NoiseConfig().inconsistency_rate:.0%} "
             "of shipments.", "",
             "## 1. Field-level accuracy by document type", "",
             "Exact match against generator ground truth. A field the generator omitted is",
             "scored correct only if the extractor also returns nothing.", ""]

    all_fields = sorted({f for v in base.accuracy.values() for f in v["fields"]})
    rows = []
    for field in all_fields:
        row = [f"`{field}`"]
        for dt in ("commercial_invoice", "packing_list", "bill_of_lading"):
            v = base.accuracy[dt]["fields"].get(field)
            row.append("-" if v is None else f"{100 * v:.1f}%")
        rows.append(row)
    rows.append(["**macro mean**"] + [
        f"**{100 * base.accuracy[dt]['macro_field_accuracy']:.1f}%**"
        for dt in ("commercial_invoice", "packing_list", "bill_of_lading")])
    lines += [_md_table(["field", "commercial invoice", "packing list", "bill of lading"],
                        rows), "",
              f"Document-level accuracy (every field *and* every line item correct): "
              f"**{100 * doc_acc:.1f}%** of {n_docs} documents.", ""]

    lines += ["## 2. Straight-through processing against the confidence threshold", "",
              "`stp` is the share of documents auto-approved; `error` is the share of those",
              "auto-approved documents that contain at least one wrong field.", ""]
    rows = []
    for t in REPORT_THRESHOLDS:
        p = min(base.points, key=lambda x: abs(x.threshold - t))
        rows.append([f"{p.threshold:.2f}", f"{100 * p.stp_rate:.1f}%",
                     f"{100 * p.error_rate:.2f}%", f"{p.precision:.3f}",
                     f"{p.recall:.3f}", p.n_auto, p.n_auto_wrong])
    lines += [_md_table(["threshold", "STP rate", "escaped error", "precision", "recall",
                         "n auto", "n auto wrong"], rows), ""]

    lines += ["## 3. STP at a fixed error budget, by second-pass policy", "",
              "`confirm` controls when the LLM pass is asked to re-read a field the rules",
              "already resolved: never, on the money/weight/date fields only, or on every",
              "field. Cost is provider calls per document.", ""]
    rows = []
    for confirm in ("none", "high_value", "all"):
        out = base if confirm == "high_value" else run(n, args.seed, confirm=confirm)
        cells = []
        for b in BUDGETS:
            op = operating_point(out.points, b)
            cells.append("infeasible" if op is None
                         else f"{100 * op.stp_rate:.1f}% @ t={op.threshold:.2f}")
        rows.append([f"`{confirm}`", f"{out.llm_calls / n_docs:.2f}"] + cells)
    lines += [_md_table(["confirm policy", "LLM calls/doc"] +
                        [f"budget {100 * b:.0f}%" for b in BUDGETS], rows), ""]

    lines += ["## 4. Three-way discrepancy detection", "",
              "Scored against the discrepancies the generator seeded. Only `major` and",
              "`critical` alerts count. Reconciliation is suppressed on tables the",
              "extractor could not read cleanly, which trades recall for precision.", ""]
    det = base.detection
    rows = [[f"`{k}`", v["seeded"], v["detected"], f"{100 * v['rate']:.1f}%"]
            for k, v in det["by_kind"].items()]
    lines += [_md_table(["discrepancy kind", "seeded", "detected", "detection rate"], rows),
              "",
              f"Overall: precision **{det['precision']:.3f}**, recall "
              f"**{det['recall']:.3f}** "
              f"({det['true_positives']} true, {det['false_negatives']} missed, "
              f"{det['false_positives']} false alerts).", ""]

    lines += ["## 5. Sensitivity to OCR corruption", "",
              "Field omission and cross-document inconsistency held at their defaults.", ""]
    rows = []
    for rate in (0.000, 0.003, 0.006, 0.012):
        out = base if abs(rate - 0.006) < 1e-9 else run(
            n, args.seed, noise=NoiseConfig(char_corruption_rate=rate))
        op5 = operating_point(out.points, 0.05)
        rows.append([f"{rate:.3f}",
                     f"{100 * sum(out.correct) / len(out.correct):.1f}%",
                     "infeasible" if op5 is None else f"{100 * op5.stp_rate:.1f}%",
                     f"{out.detection['recall']:.3f}",
                     f"{out.detection['precision']:.3f}"])
    lines += [_md_table(["corruption rate", "doc accuracy", "STP @ 5% budget",
                         "recon recall", "recon precision"], rows), ""]

    figure = stp_curve(base, os.path.join(ROOT, "docs", "stp_curve.png"),
                       error_budget=0.05)
    lines += [f"Figure: `docs/{os.path.basename(figure)}`", "",
              f"Total runtime {time.time() - t0:.1f}s on one core, no network, no API key.",
              ""]

    path = os.path.join(HERE, "results.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {path}")
    print(f"wrote {figure}")
    op = operating_point(base.points, 0.05)
    print(f"doc accuracy {100 * doc_acc:.1f}%  |  operating point @5% budget: "
          f"{op if op is None else f'{100 * op.stp_rate:.1f}% STP at t={op.threshold:.2f}'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
