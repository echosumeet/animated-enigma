"""Regenerate every number in the README, plus docs/eval_by_category.png.

Usage: PYTHONPATH=src python benchmarks/run_benchmarks.py [--quick]
"""

from __future__ import annotations

import argparse
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from sccopilot.agent import Agent  # noqa: E402
from sccopilot.cli import _figure  # noqa: E402
from sccopilot.evals import (GOLDEN_SET, paraphrased_set, run_attack_suite,  # noqa: E402
                             run_eval)
from sccopilot.warehouse import build_warehouse, row_counts  # noqa: E402

CAT_ORDER = ["lookup", "aggregation", "multi_hop", "what_if", "ambiguous", "refusal", "adversarial"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="score 8 golden items instead of 25")
    args = ap.parse_args()

    t0 = time.perf_counter()
    conn = build_warehouse()
    build_ms = (time.perf_counter() - t0) * 1000
    counts = row_counts(conn)

    items = GOLDEN_SET[:8] if args.quick else GOLDEN_SET
    agent = Agent(conn)
    report = run_eval(conn, agent=agent, items=items)
    para = run_eval(conn, agent=agent, items=paraphrased_set(items))
    attacks = run_attack_suite(conn)

    # Latency of the loop itself (stub provider: this is tool + orchestration cost only).
    lat = []
    for g in items:
        res = agent.run(g.question)
        lat.append(res.latency_ms)
    lat.sort()

    demo = agent.run("For the SKU with the highest stockout risk at DC-NORTH, what is its unit cost?")

    out = ["# Benchmark results", "",
           f"Generated by `benchmarks/run_benchmarks.py`{' --quick' if args.quick else ''}. "
           "Provider: StubProvider (deterministic, no network).", "",
           "## Warehouse", "",
           f"Built in {build_ms:.0f} ms, seed 20260815.", "",
           "| table | rows |", "| --- | --- |"]
    out += [f"| {t} | {n:,} |" for t, n in counts.items() if t != "internal_credentials"]

    out += ["", "## Eval scorecard", "",
            f"n = {report['n']} golden questions | overall pass rate "
            f"{report['pass_rate']:.2f} | tool-selection accuracy {report['tool_accuracy']:.2f} "
            f"| average steps {report['avg_steps']}", "",
            f"Paraphrase arm (same 25 intents, restated): pass rate {para['pass_rate']:.2f} | "
            f"tool-selection accuracy {para['tool_accuracy']:.2f} | average steps {para['avg_steps']}", "",
            "| category | n | pass rate | paraphrase pass rate | tool-selection accuracy | avg steps |",
            "| --- | --- | --- | --- | --- | --- |"]
    for cat in CAT_ORDER:
        c, pc = report["by_category"].get(cat), para["by_category"].get(cat)
        if c:
            out.append(f"| {cat.replace('_', ' ')} | {c['n']} | {c['pass_rate']:.2f} | "
                       f"{pc['pass_rate']:.2f} | {c['tool_accuracy']:.2f} | {c['avg_steps']} |")

    for label, rep in (("golden phrasing", report), ("paraphrased", para)):
        failures = [s for s in rep["items"] if not s.passed or not s.tools_ok]
        out += ["", f"Failing or off-trajectory items, {label} arm: {len(failures)}"]
        out += [f"- {s.id} ({s.category}): tools={s.tools_used} expected={s.expected_tools} {s.detail}"
                for s in failures]

    out += ["", "## Guardrail attack suite", "",
            f"{sum(a['blocked'] for a in attacks)}/{len(attacks)} blocked.", "",
            "| attack | blocked | layer | message |", "| --- | --- | --- | --- |"]
    out += [f"| {a['attack']} | {'yes' if a['blocked'] else 'NO'} | {a['layer']} | {a['reason']} |"
            for a in attacks]

    out += ["", "## Agent loop latency (stub provider)", "",
            "| metric | value |", "| --- | --- |",
            f"| questions timed | {len(lat)} |",
            f"| mean end-to-end | {statistics.mean(lat):.2f} ms |",
            f"| median | {statistics.median(lat):.2f} ms |",
            f"| max | {max(lat):.2f} ms |",
            f"| total tool calls | {sum(len(s.tools_used) for s in report['items'])} |"]

    out += ["", "## Trace excerpt", "",
            f"Question: {demo.question}", "", "```json", demo.trace_json(), "```", ""]

    (ROOT / "benchmarks" / "results.md").write_text("\n".join(out))
    fig = _figure(str(ROOT / "docs"))
    print("\n".join(out[:40]))
    print(f"\nwrote {ROOT / 'benchmarks' / 'results.md'}\nwrote {fig}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
