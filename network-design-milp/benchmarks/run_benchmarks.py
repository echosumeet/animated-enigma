"""Regenerate every number quoted in the README.

Run from the repository root:

    PYTHONPATH=src python benchmarks/run_benchmarks.py

Writes ``benchmarks/results.md`` and prints the same content. Everything is
deterministic given the seeds below; wall-clock timings are the only values
that move between machines.
"""

from __future__ import annotations

import platform
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402
import scipy  # noqa: E402

from netdesign import __version__  # noqa: E402
from netdesign.facility_location import (  # noqa: E402
    brute_force_uflp,
    dc_location_subproblem,
    uncapacitated_facility_location,
)
from netdesign.greenfield import (  # noqa: E402
    evaluate_open_set,
    greenfield_open_set,
    solve_with_cutoff,
)
from netdesign.instances import demand_scenarios, generate_instance  # noqa: E402
from netdesign.network_flow import NetworkDesignModel, NetworkOptions, solve_network_design  # noqa: E402
from netdesign.reporting import cost_breakdown, flow_by_echelon, markdown_table  # noqa: E402
from netdesign.scenarios import elasticity, sensitivity_sweep, stability_profile  # noqa: E402
from netdesign.stochastic import solve_two_stage  # noqa: E402

SEED = 7
SCENARIO_SEED = 11
N_SCENARIOS = 12
OUT = ROOT / "benchmarks" / "results.md"


def section(title: str) -> str:
    return f"\n## {title}\n"


def main() -> int:
    t_start = time.perf_counter()
    lines: list[str] = []
    add = lines.append

    inst = generate_instance(seed=SEED)
    add("# Benchmark results")
    add("")
    add(
        "Generated by `benchmarks/run_benchmarks.py`. Every table in the README is "
        "copied from this file."
    )
    add("")
    add(
        f"`netdesign {__version__}` · python {platform.python_version()} · "
        f"numpy {np.__version__} · scipy {scipy.__version__} (HiGHS)"
    )

    # ---------------------------------------------------------------- instance
    add(section("Instance"))
    add(f"`generate_instance(seed={SEED})` - " + inst.summary())
    add("")
    ledger_rows = [
        ["suppliers", len(inst.suppliers), f"{sum(inst.supply.values()):,.0f} units available"],
        [
            "plants",
            len(inst.plants),
            f"{sum(p.capacity for p in inst.plants):,.0f} units capacity, "
            f"fixed {sum(p.fixed_cost for p in inst.plants):,.0f}/period if all open",
        ],
        [
            "DC candidates",
            len(inst.dcs),
            f"{sum(d.capacity for d in inst.dcs):,.0f} units throughput, "
            f"fixed {min(d.fixed_cost for d in inst.dcs):,.0f}-"
            f"{max(d.fixed_cost for d in inst.dcs):,.0f}/period each",
        ],
        ["demand zones", len(inst.zones), f"{inst.total_demand():,.0f} units/period"],
        ["lanes x modes", len(inst.lanes), ", ".join(m.id for m in inst.modes)],
    ]
    add(markdown_table(["echelon", "count", "scale"], ledger_rows))

    # ----------------------------------------------------------- deterministic
    add(section("Deterministic optimum"))
    builder = NetworkDesignModel(inst, NetworkOptions())
    base, _ = builder.solve()
    lp = builder.lp_bound()
    add(
        f"**Total cost {base.objective:,.0f} per period**, {len(base.open_dcs)} of "
        f"{len(inst.dcs)} DCs open (`{', '.join(base.open_dcs)}`) and "
        f"{len(base.open_plants)} of {len(inst.plants)} plants "
        f"(`{', '.join(base.open_plants)}`). Solved in {base.runtime:.2f}s; "
        f"model has {base.model_stats['variables']:,} variables "
        f"({base.model_stats['binaries']} binary), "
        f"{base.model_stats['constraints']:,} rows, "
        f"{base.model_stats['nonzeros']:,} nonzeros."
    )
    add("")
    add(
        markdown_table(
            ["cost bucket", "per period", "share"],
            [[label, f"{cost:,.0f}", f"{share:.1f}%"] for label, cost, share in cost_breakdown(base)]
            + [["**total**", f"{sum(base.costs.values()):,.0f}", "100.0%"]],
        )
    )
    add("")
    add(
        markdown_table(
            ["echelon", "mode", "lanes used", "units", "cost", "cost/unit"],
            [
                [
                    r["echelon"],
                    r["mode"],
                    r["lanes"],
                    f"{float(r['units']):,.0f}",
                    f"{float(r['cost']):,.0f}",
                    f"{float(r['cost_per_unit']):.2f}",
                ]
                for r in flow_by_echelon(base, inst)
            ],
        )
    )
    add("")
    add(
        f"Demand-weighted last-leg distance {base.demand_weighted_km:,.0f} km; "
        f"average DCs serving a zone "
        f"{sum(len(m) for m in base.zone_service.values()) / len(base.zone_service):.2f}."
    )

    # ------------------------------------------------------------ formulations
    add(section("Formulation strength"))
    add(
        "Same feasible integer set in every row - only the linking constraints differ. "
        "The integrality gap is `(MILP - LP) / MILP` at the root."
    )
    add("")
    form_rows = []
    variants = [
        ("disaggregated link, tight M", dict(disaggregated_link=True, big_m_scale=1.0)),
        ("aggregate link, tight M", dict(disaggregated_link=False, big_m_scale=1.0)),
        ("aggregate link, M x10", dict(disaggregated_link=False, big_m_scale=10.0)),
        ("aggregate link, M x100", dict(disaggregated_link=False, big_m_scale=100.0)),
    ]
    for label, opts in variants:
        b = NetworkDesignModel(inst, NetworkOptions(**opts))
        bound = b.lp_bound()
        sol, _ = b.solve()
        form_rows.append(
            [
                label,
                f"{b.model.num_constraints:,}",
                f"{bound:,.0f}",
                f"{sol.objective:,.0f}",
                f"{100 * (sol.objective - bound) / sol.objective:.2f}%",
                f"{sol.runtime:.2f}s",
            ]
        )
    add(
        markdown_table(
            ["formulation", "rows", "LP bound", "MILP optimum", "integrality gap", "MILP time"],
            form_rows,
        )
    )

    add("")
    fixed, unit_cost, demand, capacity = dc_location_subproblem(inst)
    uflp_rows = []
    for form in ("strong", "aggregated"):
        r = uncapacitated_facility_location(
            fixed, unit_cost, demand, formulation=form, with_lp_bound=True
        )
        uflp_rows.append(
            [
                f"UFLP, {form}",
                f"{r.model_stats['constraints']:,}",
                f"{r.lp_bound:,.0f}",
                f"{r.objective:,.0f}",
                f"{100 * r.integrality_gap:.2f}%",
            ]
        )
    bf, bf_set = brute_force_uflp(fixed, unit_cost, demand)
    add(
        "The same effect on the DC-to-zone sub-problem, where the optimum can be "
        "verified by enumerating all "
        f"{2 ** len(inst.dcs) - 1} open sets:"
    )
    add("")
    add(
        markdown_table(
            ["formulation", "rows", "LP bound", "MILP optimum", "integrality gap"], uflp_rows
        )
    )
    add("")
    add(
        f"Brute force over every subset agrees exactly: {bf:,.0f} with "
        f"`{', '.join(sorted(bf_set))}`."
    )

    # ------------------------------------------------------- service structure
    add(section("What service constraints cost"))
    service_rows = []
    for label, opts in [
        ("cost-optimal (no service constraint)", {}),
        ("single sourcing (one DC per zone)", dict(single_source=True)),
        ("dual sourcing, 2nd source >= 15%", dict(min_second_source_share=0.15)),
        ("dual sourcing, 2nd source >= 25%", dict(min_second_source_share=0.25)),
    ]:
        sol = solve_network_design(inst, NetworkOptions(**opts))
        delta = 100 * (sol.objective - base.objective) / base.objective
        service_rows.append(
            [
                label,
                f"{sol.objective:,.0f}",
                f"{delta:+.2f}%",
                len(sol.open_dcs),
                f"{sum(len(m) for m in sol.zone_service.values()) / len(sol.zone_service):.2f}",
                f"{sol.demand_weighted_km:,.0f}",
                f"{sol.runtime:.2f}s",
            ]
        )
    add(
        markdown_table(
            ["variant", "cost/period", "vs optimum", "DCs", "DCs/zone", "wtd km", "time"],
            service_rows,
        )
    )

    # -------------------------------------------------------- how many DCs
    add(section("How many DCs"))
    curve_rows = []
    curve: list[tuple[int, float, float]] = []
    for k in range(2, len(inst.dcs) + 1):
        sol = solve_network_design(inst, NetworkOptions(min_open_dcs=k, max_open_dcs=k))
        if sol.objective is None:
            curve_rows.append([k, sol.status, "-", "-", "-", "-"])
            continue
        curve.append((k, float(sol.objective), sol.demand_weighted_km))
        curve_rows.append(
            [
                k,
                f"{sol.objective:,.0f}",
                f"{100 * (sol.objective - base.objective) / base.objective:+.2f}%",
                f"{sol.costs['dc_fixed']:,.0f}",
                f"{sol.costs['transport_outbound']:,.0f}",
                f"{sol.demand_weighted_km:,.0f}",
            ]
        )
    add(
        markdown_table(
            ["DCs open", "cost/period", "vs optimum", "DC fixed", "outbound transport", "wtd km"],
            curve_rows,
        )
    )
    add("")
    add(
        "The minimum-volume-if-open threshold (30% of each site's capacity) is what "
        "makes the larger networks infeasible: opening a site commits volume to it in "
        "every period."
    )

    # ---------------------------------------------------------- greenfield
    add(section("Greenfield heuristic vs the MILP"))
    gf_rows = []
    for p in (2, 3, 4, 5):
        gf = greenfield_open_set(inst, p, seed=3)
        costed = evaluate_open_set(inst, gf.snapped_dcs)
        gf_rows.append(
            [
                p,
                " ".join(gf.snapped_dcs),
                f"{gf.weighted_km:,.0f}",
                f"{costed.objective:,.0f}" if costed.is_optimal else costed.status,
                f"{100 * (costed.objective - base.objective) / base.objective:+.2f}%"
                if costed.is_optimal
                else "-",
            ]
        )
    add(
        markdown_table(
            ["p", "snapped DCs", "wtd km to center", "costed", "vs MILP optimum"], gf_rows
        )
    )
    add("")
    best_gf = greenfield_open_set(inst, 3, seed=3)
    ub = evaluate_open_set(inst, best_gf.snapped_dcs).objective
    t0 = time.perf_counter()
    plain = solve_network_design(inst)
    t_plain = time.perf_counter() - t0
    t0 = time.perf_counter()
    cut, _ = solve_with_cutoff(inst, upper_bound=ub)
    t_cut = time.perf_counter() - t0
    add(
        f"Using the p=3 heuristic cost ({ub:,.0f}) as an objective cutoff: "
        f"{t_cut:.2f}s with the cutoff vs {t_plain:.2f}s without, same optimum "
        f"({cut.objective:,.0f}). `scipy.optimize.milp` has no warm-start hook, and on an "
        "instance this size HiGHS finds a good incumbent unaided, so the cutoff buys "
        "nothing here."
    )

    # ---------------------------------------------------------- stochastic
    add(section("Two-stage stochastic design: VSS and EVPI"))
    scen, probs = demand_scenarios(inst, n_scenarios=N_SCENARIOS, seed=SCENARIO_SEED)
    totals = sorted(sum(s.values()) for s in scen)
    t0 = time.perf_counter()
    st = solve_two_stage(inst, scen, probs)
    t_stoch = time.perf_counter() - t0
    add(
        f"{N_SCENARIOS} equiprobable demand scenarios from the three-level shock model "
        f"(national 20%, regional 22%, zone 18% standard deviation). Scenario totals span "
        f"{totals[0]:,.0f} to {totals[-1]:,.0f} units/period against a nominal "
        f"{inst.total_demand():,.0f}. Unmet demand is priced at "
        f"{NetworkOptions().unmet_penalty:.0f} per unit. "
        f"{2 * N_SCENARIOS + 2} MILP solves in {t_stoch:.1f}s."
    )
    add("")
    add(
        markdown_table(
            ["measure", "expected cost/period", "network"],
            [
                ["WS - wait-and-see (perfect information)", f"{st.ws:,.0f}", "varies by scenario"],
                ["RP - stochastic here-and-now", f"{st.rp:,.0f}", " ".join(st.rp_solution.open_dcs)],
                [
                    "EEV - mean-value design, lived with",
                    f"{st.eev:,.0f}",
                    " ".join(st.ev_solution.open_dcs),
                ],
            ],
        )
    )
    add("")
    add(
        markdown_table(
            ["headline", "value", "% of RP", "reading"],
            [
                [
                    "VSS = EEV - RP",
                    f"{st.vss:,.0f}",
                    f"{st.vss_pct:.2f}%",
                    "what modelling the uncertainty is worth",
                ],
                [
                    "EVPI = RP - WS",
                    f"{st.evpi:,.0f}",
                    f"{st.evpi_pct:.2f}%",
                    "ceiling on any forecast investment",
                ],
            ],
        )
    )
    add("")
    add(
        f"Only {100 * st.network_stability:.0f}% of the wait-and-see solutions choose the same "
        f"DC set as the stochastic solution, which is the honest signal that the site "
        f"decision is genuinely uncertain rather than merely uncertain in flow."
    )

    # ---------------------------------------------------------- sensitivity
    add(section("Sensitivity sweep"))
    runs = sensitivity_sweep(inst)
    prof = stability_profile(runs)
    slope = elasticity(runs, "demand_multiplier")
    grid_rows = []
    for r in runs:
        grid_rows.append(
            [
                f"{r.params['demand_multiplier']:g}",
                f"{r.params['cost_multiplier']:g}",
                f"{r.objective:,.0f}" if r.objective else r.status,
                r.n_dcs,
                " ".join(r.open_dcs),
                f"{r.demand_weighted_km:,.0f}",
            ]
        )
    add(
        markdown_table(
            ["demand x", "transport x", "cost/period", "DCs", "open set", "wtd km"], grid_rows
        )
    )
    add("")
    add(
        f"{prof['n_runs']} runs produced {prof['distinct_networks']} distinct networks, "
        f"mean {prof['mean_dcs']:.1f} DCs open."
    )
    add("")
    add(
        markdown_table(
            ["bucket", "DCs", "meaning"],
            [
                ["core", ", ".join(prof["core"]) or "-", "open in >=90% of runs - commit"],
                ["swing", ", ".join(prof["swing"]) or "-", "the actual decision"],
                ["out", ", ".join(prof["out"]) or "-", "never open - stop discussing"],
            ],
        )
    )
    add("")
    add(
        f"Cost elasticity to demand (log-log slope): {slope:.2f}. Below 1 means fixed cost "
        "is being spread over more volume; above 1 means lumpy capacity is being added "
        "faster than volume grows. It is the number to check before believing a savings "
        "case built on a volume assumption."
    )

    # ---------------------------------------------------------- scaling
    add(section("Model size and solve time"))
    scale_rows = []
    for label, kwargs in [
        ("small", dict(seed=7, n_dcs=5, n_zones=12, n_commodities=1, n_plants=3)),
        ("default", dict(seed=7)),
        (
            "large",
            dict(
                seed=21,
                n_suppliers=4,
                n_plants=6,
                n_dcs=16,
                n_zones=60,
                n_commodities=3,
                total_demand_units=600_000.0,
                dc_capacity_slack=0.22,
            ),
        ),
    ]:
        big = generate_instance(**kwargs)
        b = NetworkDesignModel(big, NetworkOptions())
        bound = b.lp_bound()
        sol, _ = b.solve(time_limit=600)
        s = b.model.stats()
        scale_rows.append(
            [
                label,
                f"{len(big.dcs)}x{len(big.zones)}x{len(big.commodities)}",
                f"{s['variables']:,}",
                f"{s['binaries']:,}",
                f"{s['constraints']:,}",
                f"{s['nonzeros']:,}",
                f"{100 * (sol.objective - bound) / sol.objective:.2f}%",
                f"{sol.runtime:.2f}s",
            ]
        )
    add(
        markdown_table(
            ["instance", "DCs x zones x SKUs", "vars", "binary", "rows", "nonzeros", "root gap", "MILP time"],
            scale_rows,
        )
    )

    add("")
    add(f"_Total benchmark runtime {time.perf_counter() - t_start:.1f}s._")

    text = "\n".join(lines) + "\n"
    OUT.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
