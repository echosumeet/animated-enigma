"""Regenerate every number in the README, plus the figure.

Usage:
    PYTHONPATH=src python benchmarks/run_benchmarks.py [--quick]
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402

from etarisk import __version__  # noqa: E402
from etarisk.drift import psi_table  # noqa: E402
from etarisk.figures import calibration_figure  # noqa: E402
from etarisk.generate import GeneratorConfig, describe_distribution  # noqa: E402
from etarisk.pipeline import run_pipeline  # noqa: E402


def _md(frame: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    fmt = frame.copy()
    for c in fmt.columns:
        if pd.api.types.is_float_dtype(fmt[c]):
            fmt[c] = fmt[c].map(floatfmt.format)
    head = "| " + " | ".join(str(c) for c in fmt.columns) + " |"
    rule = "| " + " | ".join("---" for _ in fmt.columns) + " |"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in fmt.to_numpy()]
    return "\n".join([head, rule, *rows])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="smaller panel, fewer trees")
    args = ap.parse_args()

    n = 15_000 if args.quick else 60_000
    iters = 120 if args.quick else 300
    t0 = time.perf_counter()
    res = run_pipeline(GeneratorConfig(n_shipments=n), max_iter=iters)
    elapsed = time.perf_counter() - t0
    m = res.metrics
    shape = describe_distribution(res.data)
    drift = psi_table(res.X["train_scoring"], res.X["test"])
    fig = calibration_figure(m, ROOT / "docs")

    d, d_raw = m["decision"], m["decision_uncalibrated"]
    lines = [
        "# Benchmark results",
        "",
        f"Generated by `benchmarks/run_benchmarks.py` (etarisk {__version__}). "
        f"Wall clock {elapsed:.1f}s for the whole pipeline on one core.",
        "",
        f"Panel: {m['n_shipments']:,} shipments over a 15-lane, 4-mode, 7-carrier synthetic "
        f"network; temporal split {m['n_train']:,} train / {m['n_calib']:,} calibration / "
        f"{m['n_test']:,} test. Test-block late rate {m['late_rate_test']:.3f}.",
        "",
        "## Transit-time distribution",
        "",
        _md(pd.DataFrame([{k: v for k, v in shape.items() if k != "n"}]), "{:.2f}"),
        "",
        "## Point ETA accuracy (held-out test block)",
        "",
        _md(
            pd.DataFrame(
                [
                    {"model": "quoted transit time", "mae_h": m["quoted_mae_h"], "bias_h": m["quoted_bias_h"]},
                    {"model": "HistGradientBoosting (MAE loss)", "mae_h": m["eta_mae_h"], "bias_h": m["eta_bias_h"]},
                ]
            ),
            "{:.2f}",
        ),
        "",
        "### MAE by planned-transit horizon",
        "",
        _md(m["mae_by_horizon"], "{:.2f}"),
        "",
        "## Split-conformal coverage",
        "",
        _md(m["coverage"]),
        "",
        "## Delay-risk calibration",
        "",
        _md(
            pd.DataFrame(
                [
                    {"scoring": "raw GBT", "brier": m["brier_raw"], "ece": m["ece_raw"]},
                    {"scoring": "isotonic", "brier": m["brier_calibrated"], "ece": m["ece_calibrated"]},
                ]
            ),
            "{:.4f}",
        ),
        "",
        f"Figure: `{fig.relative_to(ROOT)}`",
        "",
        "## Decision layer vs fixed carrier-scorecard rule",
        "",
        _md(
            pd.DataFrame(
                [
                    {"policy": "fixed rule", "cost_per_shipment": d["baseline_cost_per_shipment"], "saved_pct": 0.0},
                    {"policy": "model, uncalibrated p", "cost_per_shipment": d_raw["model_cost_per_shipment"], "saved_pct": d_raw["saved_pct"]},
                    {"policy": "model, isotonic p", "cost_per_shipment": d["model_cost_per_shipment"], "saved_pct": d["saved_pct"]},
                    {"policy": "oracle (knows the outcome)", "cost_per_shipment": d["oracle_cost_per_shipment"], "saved_pct": 100.0 * (d["baseline_cost_per_shipment"] - d["oracle_cost_per_shipment"]) / d["baseline_cost_per_shipment"]},
                ]
            ),
            "{:.2f}",
        ),
        "",
        f"Action thresholds implied by the cost matrix: notify above "
        f"p={m['cost_thresholds']['nothing_to_notify']:.3f}, expedite above "
        f"p={m['cost_thresholds']['notify_to_expedite']:.3f}. The model expedites "
        f"{100 * d['model_share_expedite']:.1f}% of shipments against the fixed rule's "
        f"{100 * d['baseline_share_expedite']:.1f}%, and captures "
        f"{d['pct_of_oracle_gap_captured']:.1f}% of the gap to the oracle.",
        "",
        "## Feature drift, train block vs test block (PSI)",
        "",
        _md(drift.head(8), "{:.4f}"),
        "",
    ]
    out = ROOT / "benchmarks" / "results.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwrote {out} and {fig}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
