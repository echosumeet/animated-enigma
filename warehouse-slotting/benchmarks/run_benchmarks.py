"""Regenerate every number quoted in the README.

    PYTHONPATH=src python benchmarks/run_benchmarks.py [--quick]

Writes ``benchmarks/results.md``. Nothing here is cached: the instance, the
slotting, the routing and the exact reference are all recomputed from the seed
on every run, so a number in the README that cannot be reproduced by this
script is a bug in the README.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from slotting import __version__, run_benchmark  # noqa: E402
from slotting.benchmark import BenchmarkReport  # noqa: E402

POLICY_LABELS = {
    "s_shape": "S-shape",
    "return": "Return",
    "midpoint": "Midpoint",
    "largest_gap": "Largest gap",
    "two_opt": "2-opt",
}


def table(header: list[str], rows: list[list[str]]) -> str:
    align = ["---"] + ["---:"] * (len(header) - 1)
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def fmt_travel_table(report: BenchmarkReport, policies: list[str]) -> str:
    base_name = report.runs[0].name
    header = ["Slotting policy"] + [POLICY_LABELS[p] for p in policies] + ["vs baseline (2-opt)"]
    rows = []
    for run in report.runs:
        t = report.travel_out_of_sample[run.name]
        cut = report.reduction(run.name, "two_opt")
        rows.append(
            [run.name]
            + [f"{t[p] / 1000:,.1f}" for p in policies]
            + ["baseline" if run.name == base_name else f"-{100 * cut:.1f}%"]
        )
    return table(header, rows)


def fmt_gap_table(report: BenchmarkReport, policies: list[str]) -> str:
    header = ["Routing heuristic", "Mean gap", "p90 gap", "Max gap", "Tours"]
    rows = []
    for p in policies:
        g = report.gaps_best[p]
        rows.append(
            [
                POLICY_LABELS[p],
                f"{100 * g['mean_gap']:.2f}%",
                f"{100 * g['p90_gap']:.2f}%",
                f"{100 * g['max_gap']:.2f}%",
                f"{int(g['n'])}",
            ]
        )
    return table(header, rows)


def fmt_batching_table(report: BenchmarkReport) -> str:
    header = ["Batching policy", "Tours", "Total km", "m / order", "m / line", "Aisles / tour"]
    rows = [
        [
            r.policy,
            f"{r.n_batches:,}",
            f"{r.total_distance_m / 1000:,.1f}",
            f"{r.distance_per_order_m:,.1f}",
            f"{r.distance_per_line_m:,.1f}",
            f"{r.mean_aisles_per_batch:,.1f}",
        ]
        for r in report.batching
    ]
    return table(header, rows)


def render(report: BenchmarkReport, policies: list[str], quick: bool) -> str:
    d = report.instance
    best = report.best_run
    parts: list[str] = []
    parts.append("# Benchmark results\n")
    parts.append(
        f"Generated by `benchmarks/run_benchmarks.py` (slotting {__version__}) on "
        f"{date.today().isoformat()}. Every figure below is the output of that run; "
        f"re-running it reproduces this file exactly.\n"
    )
    if quick:
        parts.append("**Quick mode** — reduced instance and iteration counts, not the headline run.\n")

    parts.append("## Instance\n")
    parts.append(
        table(
            ["Property", "Value"],
            [
                ["Warehouse", f"{int(d['aisles'])} aisles x {int(d['bays'])} bays x "
                              f"{int(d['levels'])} levels = {int(d['locations']):,} pick faces"],
                ["Aisle run", f"{d['aisle_length_m']:.1f} m"],
                ["SKUs", f"{int(d['skus']):,}"],
                ["Orders", f"{int(d['orders']):,} ({int(d['orders'] * 0.6):,} fit / "
                           f"{int(d['orders'] - int(d['orders'] * 0.6)):,} score)"],
                ["Mean lines per order", f"{d['mean_lines']:.2f}"],
                ["Single-line orders", f"{100 * d['single_line_share']:.1f}%"],
                ["Picks from fastest 20% of SKUs", f"{100 * d['top20pct_pick_share']:.1f}%"],
                ["Picks from fastest 5% of SKUs", f"{100 * d['top5pct_pick_share']:.1f}%"],
                ["Hazmat SKUs (floor level only)", f"{int(d['hazmat_skus'])}"],
                ["Within-family co-occurrence lift",
                 f"{report.lift['within_family_lift']:.2f}x"],
            ],
        )
    )
    parts.append(
        "\nDemand is Zipf over SKUs; orders are drawn with an overdispersed basket size "
        "and a family theme, which is what puts real affinity structure in the stream. "
        "Slotting sees the first 60% of orders only; every travel number below is "
        "measured on the held-out last 40%.\n"
    )

    parts.append("## Picker travel by slotting policy\n")
    parts.append("Total kilometres walked over the held-out order stream, one tour per order.\n")
    parts.append(fmt_travel_table(report, policies))
    n_fit = int(d["orders"] * 0.6)
    n_score = int(d["orders"]) - n_fit
    in_per = report.travel_in_sample[best]["two_opt"] / n_fit
    out_per = report.travel_out_of_sample[best]["two_opt"] / n_score
    parts.append(
        f"\nBest slotting policy on this instance: **{best}**, at "
        f"-{100 * report.reduction(best, 'two_opt'):.1f}% against the unslotted baseline.\n"
        f"\nFit-period travel under that slotting is {in_per:,.1f} m per order against "
        f"{out_per:,.1f} m per order on the held-out period, so the benefit decays "
        f"{100 * (out_per / in_per - 1):.1f}% once demand has drifted away from the ranking "
        "the slotting was built on. Scoring on the fitting period would have reported the "
        f"lower number.\n"
    )

    parts.append("## Routing optimality gap\n")
    parts.append(
        "Excess over the exact route for the same pick set, measured tour by tour under "
        "the best slotting. The exact reference is the aisle-by-aisle dynamic program "
        "(Ratliff & Rosenthal 1983); on every tour small enough for it, Held-Karp is run "
        "as well and asserted to agree to 1e-6, so the reference is backed by two "
        "independent exact methods.\n"
    )
    parts.append(fmt_gap_table(report, policies))
    parts.append("\nThe same table under the unslotted baseline, for comparison:\n")
    parts.append(
        table(
            ["Routing heuristic", "Mean gap", "p90 gap"],
            [
                [POLICY_LABELS[p],
                 f"{100 * report.gaps_baseline[p]['mean_gap']:.2f}%",
                 f"{100 * report.gaps_baseline[p]['p90_gap']:.2f}%"]
                for p in policies
            ],
        )
    )

    parts.append("\n## Order batching\n")
    parts.append(f"Under the best slotting ({best}), cart limits 6 orders / 24 lines / 0.75 m3.\n")
    parts.append(fmt_batching_table(report))

    parts.append(f"\n---\n\nTotal wall time for this run: {report.seconds:.1f} s.\n")
    return "\n".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--quick", action="store_true", help="small instance, for smoke testing")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--gap-sample", type=int, default=400)
    args = ap.parse_args()

    policies = ["s_shape", "return", "midpoint", "largest_gap", "two_opt"]
    print(f"running benchmark (seed={args.seed}, quick={args.quick}) ...", flush=True)
    report = run_benchmark(seed=args.seed, gap_sample=args.gap_sample, quick=args.quick)

    out = ROOT / "benchmarks" / "results.md"
    out.write_text(render(report, policies, args.quick), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} in {report.seconds:.1f}s")
    print(f"best slotting: {report.best_run}")
    for run in report.runs:
        print(f"  {run.name:34s} {report.travel_out_of_sample[run.name]['two_opt'] / 1000:8.1f} km")


if __name__ == "__main__":
    main()
